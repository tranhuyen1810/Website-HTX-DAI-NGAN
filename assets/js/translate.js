// Current language - default to English on mobile, Vietnamese on desktop
let currentLang = 'en'; // Changed default to English

// Initialize translation system
function initTranslation() {
    console.log('Translation system initializing...');
    
    // Check if mobile device
    const isMobile = window.innerWidth <= 900;
    console.log('Is mobile:', isMobile);
    
    // Get language from localStorage or use default based on device
    const savedLang = localStorage.getItem('preferredLanguage');
    if (savedLang && (savedLang === 'vi' || savedLang === 'en')) {
        currentLang = savedLang;
    } else {
        // Default: English for all devices
        currentLang = 'en';
    }
    
    console.log('Current language:', currentLang);
    setLanguage(currentLang);
    
    // Add event listeners to language buttons (both old and new styles)
    const langButtons = document.querySelectorAll('.lang-btn, .lang-btn-icon');
    console.log('Found language buttons:', langButtons.length);
    
    langButtons.forEach(btn => {
        // Use both click and touchend for mobile compatibility
        const handleLanguageChange = function(e) {
            e.preventDefault();
            e.stopPropagation();
            const lang = this.getAttribute('data-lang');
            console.log('Language button clicked:', lang);
            setLanguage(lang);
            
            // Update active state for all language buttons
            document.querySelectorAll('.lang-btn, .lang-btn-icon').forEach(b => b.classList.remove('active'));
            document.querySelectorAll(`[data-lang="${lang}"]`).forEach(b => b.classList.add('active'));
            
            // Save preference
            localStorage.setItem('preferredLanguage', lang);
            console.log('Language saved:', lang);
        };
        
        btn.addEventListener('click', handleLanguageChange);
        btn.addEventListener('touchend', handleLanguageChange);
    });
}

// Set language and translate all elements
function setLanguage(lang) {
    currentLang = lang;
    
    // Find all elements with data-translate attribute
    const elements = document.querySelectorAll('[data-translate]');
    
    elements.forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            // Check if translation contains HTML (like <br>)
            if (translations[lang][key].includes('<br>')) {
                element.innerHTML = translations[lang][key];
            } else {
                // For input elements, update placeholder
                if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                    element.placeholder = translations[lang][key];
                } else {
                    element.textContent = translations[lang][key];
                }
            }
        }
    });
    
    // Update language button states
    const langButtons = document.querySelectorAll('.lang-btn, .lang-btn-icon');
    langButtons.forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

// Initialize when DOM is ready
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initTranslation);
} else {
    initTranslation();
}
